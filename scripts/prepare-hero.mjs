import { createHash } from 'node:crypto'
import {
  closeSync, copyFileSync, existsSync, lstatSync, mkdirSync, mkdtempSync,
  openSync, readFileSync, readdirSync, realpathSync, renameSync, rmSync,
  statSync, unlinkSync, writeFileSync,
} from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { spawnSync } from 'node:child_process'
import { fileURLToPath } from 'node:url'

// All paths are anchored to this script, never to the caller's working directory.
const root = realpathSync(resolve(dirname(fileURLToPath(import.meta.url)), '..'))
const source = join(root, 'assets/source/DroneVideo.mp4')
const publicDir = join(root, 'public')
const framesDir = join(publicDir, 'frames')
const mediaDir = join(publicDir, 'media')
const manifestPath = join(framesDir, 'manifest.json')
const posterPath = join(mediaDir, 'hero-poster.jpg')
const generator = 'aether-estates/prepare-hero/v1'
const jpegQuality = 4
const framePattern = /^frame_\d{4,}\.jpg$/
const frameName = (index) => `frame_${String(index).padStart(4, '0')}.jpg`
const hash = (path) => createHash('sha256').update(readFileSync(path)).digest('hex')
const mib = (bytes) => `${(bytes / 1024 ** 2).toFixed(2)} MiB`

function run(binary, args) {
  // No shell interpolation: filenames and filters are separate arguments.
  const result = spawnSync(binary, args, { encoding: 'utf8', maxBuffer: 64 * 1024 ** 2 })
  if (result.error) {
    if (result.error.code === 'ENOENT') {
      throw new Error(`${binary} is missing. On macOS, install FFmpeg with approval: brew install ffmpeg`)
    }
    throw result.error
  }
  if (result.status !== 0) {
    throw new Error(`${binary} failed (${result.status ?? result.signal}):\n${result.stderr?.trim() || 'No diagnostic output.'}`)
  }
  return result.stdout
}

function probe(args) {
  return JSON.parse(run('ffprobe', ['-v', 'error', ...args, '-of', 'json']))
}

function rational(value) {
  const [a, b = 1] = String(value ?? '').split(/[/:]/).map(Number)
  const result = a / b
  return Number.isFinite(result) && result > 0 ? result : null
}

function assertRegularFile(path) {
  const info = lstatSync(path)
  if (!info.isFile() || info.isSymbolicLink()) throw new Error(`Expected a regular, non-symlink file: ${path}`)
}

function ensureSafeDirectory(path) {
  // Check every segment we create or traverse under the canonical project root.
  if (path !== root && !path.startsWith(`${root}/`)) throw new Error(`Unsafe output path: ${path}`)
  if (path === root) return
  ensureSafeDirectory(dirname(path))
  if (!existsSync(path)) mkdirSync(path)
  const info = lstatSync(path)
  if (!info.isDirectory() || info.isSymbolicLink() || realpathSync(path) !== path) {
    throw new Error(`Refusing non-directory or symlink output: ${path}`)
  }
}

function ownedOutputs() {
  const candidates = readdirSync(framesDir).filter((name) => framePattern.test(name))
  if (!existsSync(manifestPath)) {
    if (candidates.length || existsSync(posterPath)) {
      throw new Error('Existing hero assets have no owned manifest. Refusing to overwrite them; move them aside explicitly first.')
    }
    return []
  }
  assertRegularFile(manifestPath)
  const old = JSON.parse(readFileSync(manifestPath, 'utf8'))
  if (old.generatedBy !== generator || !Number.isSafeInteger(old.frameCount) || old.frameCount < 1) {
    throw new Error('Existing manifest was not generated by this pipeline. Refusing to overwrite it.')
  }
  const expected = new Set(Array.from({ length: old.frameCount }, (_, i) => frameName(i + 1)))
  if (candidates.some((name) => !expected.has(name))) {
    throw new Error('Unexpected numbered JPEGs exist outside the previous manifest. Refusing to delete unrelated files.')
  }
  const paths = [...candidates.map((name) => join(framesDir, name)), manifestPath]
  if (existsSync(posterPath)) paths.push(posterPath)
  paths.forEach(assertRegularFile)
  return paths
}

function publish(stagedFrames, stagedPoster, oldPaths, names, staging) {
  // Back up only recognized outputs. Roll back ordinary publish failures.
  const backups = []
  const installed = []
  try {
    for (const [i, path] of oldPaths.entries()) {
      const backup = join(staging, `previous-${i}`)
      renameSync(path, backup)
      backups.push([backup, path])
    }
    for (const name of names) {
      const destination = join(framesDir, name)
      renameSync(join(stagedFrames, name), destination)
      installed.push(destination)
    }
    renameSync(stagedPoster, posterPath)
    installed.push(posterPath)
    // The manifest is published last, after all referenced assets exist.
    renameSync(join(stagedFrames, 'manifest.json'), manifestPath)
    installed.push(manifestPath)
  } catch (error) {
    for (const path of installed.reverse()) unlinkSync(path)
    for (const [backup, path] of backups.reverse()) renameSync(backup, path)
    throw error
  }
}

let staging
let lock
const lockPath = join(root, '.prepare-hero.lock')
try {
  if (!existsSync(source)) throw new Error(`Source video not found: ${source}`)
  assertRegularFile(source)
  const sourceHash = hash(source)
  const ffmpegVersion = run('ffmpeg', ['-version']).split('\n')[0]
  const ffprobeVersion = run('ffprobe', ['-version']).split('\n')[0]
  try {
    lock = openSync(lockPath, 'wx')
    writeFileSync(lock, `${process.pid}\n`)
  } catch (error) {
    if (error.code === 'EEXIST') {
      throw new Error('Another preparation may be running (.prepare-hero.lock exists). Only remove a stale lock after checking its PID.')
    }
    throw error
  }

  const metadata = probe(['-count_frames', '-show_streams', '-show_format', source])
  const video = metadata.streams.find((stream) => stream.codec_type === 'video' && !stream.disposition?.attached_pic)
  if (!video) throw new Error('No usable video stream found.')
  const sourceFps = rational(video.avg_frame_rate) ?? rational(video.r_frame_rate)
  if (!sourceFps) throw new Error('Unable to determine a positive source frame rate.')
  const durationSeconds = Number(video.duration ?? metadata.format.duration)
  if (!(durationSeconds > 0)) throw new Error('Unable to determine a positive video duration.')
  const transfer = video.color_transfer
  if (transfer === 'smpte2084' || transfer === 'arib-std-b67') {
    throw new Error('HDR source detected. Supply an approved SDR export to avoid unapproved color transformations.')
  }
  const timing = probe([
    '-select_streams', String(video.index), '-show_frames',
    '-show_entries', 'frame=best_effort_timestamp_time', source,
  ]).frames.map((frame) => Number(frame.best_effort_timestamp_time))
  if (!timing.length || timing.some((time) => !Number.isFinite(time))) {
    throw new Error('Source frame timestamps could not be verified.')
  }
  const deltas = timing.slice(1).map((time, i) => time - timing[i])
  if (deltas.some((delta) => delta <= 0)) throw new Error('Non-increasing source timestamps require manual review.')
  const variableFrameRate = deltas.some((delta) => Math.abs(delta - 1 / sourceFps) > 0.001)
  const fps = Math.min(24, sourceFps)
  const rotation = Number(video.side_data_list?.find((item) => item.rotation !== undefined)?.rotation ?? video.tags?.rotate ?? 0)
  const sourceInfo = {
    path: 'assets/source/DroneVideo.mp4', sha256: sourceHash,
    fileSizeBytes: statSync(source).size,
    containerDurationSeconds: Number(metadata.format.duration), videoDurationSeconds: durationSeconds,
    width: video.width, height: video.height,
    displayAspectRatio: video.display_aspect_ratio ?? null,
    sampleAspectRatio: video.sample_aspect_ratio ?? null,
    codec: video.codec_name, pixelFormat: video.pix_fmt,
    nominalFrameRate: video.r_frame_rate, averageFrameRate: video.avg_frame_rate,
    actualAverageFps: sourceFps, variableFrameRate,
    estimatedFrameCount: Math.round(durationSeconds * sourceFps),
    decodedFrameCount: Number(video.nb_read_frames),
    firstTimestampSeconds: timing[0], lastTimestampSeconds: timing.at(-1),
    audioPresent: metadata.streams.some((stream) => stream.codec_type === 'audio'),
    audioStreams: metadata.streams.filter((stream) => stream.codec_type === 'audio').map((stream) => ({
      codec: stream.codec_name, sampleRate: stream.sample_rate, channels: stream.channels,
    })),
    rotationDegrees: rotation, fieldOrder: video.field_order ?? null,
    colorSpace: video.color_space ?? null, colorTransfer: transfer ?? null,
    tags: video.tags ?? {}, sideData: video.side_data_list ?? [],
  }
  console.log('Verified source metadata:\n' + JSON.stringify(sourceInfo, null, 2))

  ensureSafeDirectory(framesDir)
  ensureSafeDirectory(mediaDir)
  const oldPaths = ownedOutputs()
  staging = mkdtempSync(join(root, '.hero-preparation-'))
  const stagedFrames = join(staging, 'frames')
  const stagedPoster = join(staging, 'hero-poster.jpg')
  mkdirSync(stagedFrames)
  // Fit within source dimensions, correct non-square pixels, and cap width.
  // FFmpeg applies display rotation before this filter. No crop, grade, or sharpen.
  const scale = "scale=w='trunc(min(1280,min(iw,ih*dar))/2)*2':h='trunc(ow/dar/2)*2':flags=bicubic,setsar=1"
  const filters = `setpts=PTS-STARTPTS,fps=fps=${fps}:start_time=0:round=near:eof_action=pass,${scale}`
  run('ffmpeg', [
    '-hide_banner', '-loglevel', 'error', '-nostdin', '-n', '-i', source,
    '-map', `0:${video.index}`, '-an', '-sn', '-dn', '-vf', filters,
    '-fps_mode', 'passthrough', '-c:v', 'mjpeg', '-q:v', String(jpegQuality), '-pix_fmt', 'yuvj420p',
    '-start_number', '1', join(stagedFrames, 'frame_%04d.jpg'),
  ])
  const names = readdirSync(stagedFrames).filter((name) => framePattern.test(name))
    .sort((a, b) => Number(a.slice(6, -4)) - Number(b.slice(6, -4)))
  if (!names.length || names.some((name, i) => name !== frameName(i + 1))) {
    throw new Error('Extraction did not produce a complete, sequential JPEG set.')
  }
  // Decode every generated JPEG; count and dimensions are measured, not assumed.
  run('ffmpeg', [
    '-hide_banner', '-loglevel', 'error', '-xerror', '-nostdin', '-framerate', String(fps),
    '-start_number', '1', '-i', join(stagedFrames, 'frame_%04d.jpg'), '-f', 'null', '-',
  ])
  const decoded = probe([
    '-framerate', String(fps), '-start_number', '1', '-i', join(stagedFrames, 'frame_%04d.jpg'),
    '-show_frames', '-show_entries', 'frame=width,height',
  ]).frames
  const { width, height } = decoded[0] ?? {}
  if (decoded.length !== names.length || !width || !height || width > 1280 ||
      decoded.some((frame) => frame.width !== width || frame.height !== height)) {
    throw new Error('Extracted JPEG count or dimensions failed verification.')
  }
  const portraitRotation = Math.abs(rotation) % 180 === 90
  const maxWidth = portraitRotation ? video.height : video.width
  const maxHeight = portraitRotation ? video.width : video.height
  if (width > maxWidth || height > maxHeight) throw new Error('Output unexpectedly upscaled the source.')
  if (Math.abs(names.length / fps - durationSeconds) > 1 / fps + 0.001) {
    throw new Error('Extracted timeline does not cover the video duration within one output frame.')
  }
  // Copy the first verified exterior JPEG without another lossy encoding pass.
  // A replacement source's opening composition must be visually reviewed again.
  copyFileSync(join(stagedFrames, names[0]), stagedPoster)
  const poster = probe(['-show_streams', stagedPoster]).streams[0]
  if (poster.codec_name !== 'mjpeg' || poster.width !== width || poster.height !== height) {
    throw new Error('Poster validation failed.')
  }
  const sequenceBytes = names.reduce((total, name) => total + statSync(join(stagedFrames, name)).size, 0)
  const posterBytes = statSync(stagedPoster).size
  const manifest = {
    generatedBy: generator,
    frameCount: names.length, fps, durationSeconds, width, height,
    filenamePattern: '/frames/frame_%04d.jpg',
    firstFrame: `/frames/${names[0]}`, lastFrame: `/frames/${names.at(-1)}`,
    posterUrl: '/media/hero-poster.jpg',
    startNumber: 1,
    frameTimesSeconds: names.map((_, index) => Number((index / fps).toFixed(6))),
    timingNote: 'Frame times are normalized output sample times; FFmpeg selects source frames nearest each sample.',
    sequenceBytes, averageFrameBytes: sequenceBytes / names.length, posterBytes,
    source: sourceInfo,
    processing: { jpegQuality, filters, ffmpegVersion, ffprobeVersion },
  }
  writeFileSync(join(stagedFrames, 'manifest.json'), JSON.stringify(manifest, null, 2) + '\n')
  if (hash(source) !== sourceHash) throw new Error('Source changed during processing. Outputs will not be published.')
  // Revalidate output directories and ownership immediately before mutation.
  ensureSafeDirectory(framesDir)
  ensureSafeDirectory(mediaDir)
  if (JSON.stringify(ownedOutputs()) !== JSON.stringify(oldPaths)) throw new Error('Outputs changed during preparation; refusing to publish.')
  publish(stagedFrames, stagedPoster, oldPaths, names, staging)
  const actualNames = readdirSync(framesDir).filter((name) => framePattern.test(name))
  if (actualNames.length !== manifest.frameCount) throw new Error('Published frame count differs from manifest.')
  const manifestBytes = statSync(manifestPath).size
  console.log(`\nPrepared ${names.length} frames at ${width}×${height}, ${fps} FPS.`)
  console.log(`Sequence: ${sequenceBytes} bytes (${mib(sequenceBytes)}); average: ${(sequenceBytes / names.length / 1024).toFixed(2)} KiB/frame.`)
  console.log(`Poster: ${posterBytes} bytes; total including manifest: ${sequenceBytes + posterBytes + manifestBytes} bytes (${mib(sequenceBytes + posterBytes + manifestBytes)}).`)
  console.log('All JPEGs decoded successfully; sequential names, poster, and unchanged source SHA-256 verified.')
  console.log('The source watermark remains. Review opening, middle, and final images before using a replacement source.')
} catch (error) {
  console.error(`Hero preparation failed: ${error.message}`)
  process.exitCode = 1
} finally {
  if (staging) rmSync(staging, { recursive: true, force: true })
  if (lock !== undefined) {
    closeSync(lock)
    unlinkSync(lockPath)
  }
}
